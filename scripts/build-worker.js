// Builds the static files for the Cloudflare Worker into dist-worker/:
// public/ plus src/core/ at /core/. The UI keeps talking to /api (server mode),
// which the Worker routes to the Durable Object.
import { cpSync, existsSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist-worker');

rmSync(out, { recursive: true, force: true });
cpSync(join(root, 'public'), out, { recursive: true });
cpSync(join(root, 'src/core'), join(out, 'core'), { recursive: true });

const swPath = join(out, 'sw.js');
const sw = readFileSync(swPath, 'utf8');
if (!sw.includes('__BUILD_ID__')) throw new Error('build id placeholder not found in sw.js');
const buildId = (process.env.GITHUB_SHA ?? '').slice(0, 12) || `local-${Date.now().toString(36)}`;
writeFileSync(swPath, sw.replaceAll('__BUILD_ID__', buildId));

for (const f of ['index.html', 'manifest.webmanifest', 'icons/apple-touch-icon.png', 'core/api.js']) {
  if (!existsSync(join(out, f))) throw new Error(`missing from worker build: ${f}`);
}
// Embed every file in the Worker bundle: no separate asset upload is needed.
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
};
function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}
const files = walk(out)
  .map((full) => ({ full, url: '/' + relative(out, full).split('\\').join('/') }))
  .filter((f) => !f.url.endsWith('/static-files.js'));
const lines = files.map((f) => {
  const type = TYPES[extname(f.full)] ?? 'application/octet-stream';
  const data = readFileSync(f.full).toString('base64');
  return `  ${JSON.stringify(f.url)}: { type: ${JSON.stringify(type)}, data: ${JSON.stringify(data)} },`;
});
writeFileSync(join(out, 'static-files.js'), `// Generated by scripts/build-worker.js. Do not edit.\nexport const FILES = {\n${lines.join('\n')}\n};\n`);
console.log(`Built ${out} (${files.length} files embedded)`);
